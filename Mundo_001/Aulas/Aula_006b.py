# Tipos primitivos e saída de dados

#inteiros
n = int(input('Digite um valor: '))
print(n)

#flutuantes
n = float(input('Digite um valor: '))
print(n)

#string
n = str(input('Digite um valor: '))
print(n)

#boolean
n = bool(input('Digite um valor: '))
print(n)

n = input('Digite algo: ')
print(n.isnumeric())

n = input('Digite algo: ')
print(n.isalpha())

n = input('Digite algo: ')
print(n.isalnum())
