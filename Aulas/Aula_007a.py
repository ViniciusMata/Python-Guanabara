# Operadores Aritméticos

n1 = int(input('Um valor: '))
n2 = int(input('Outro valor: '))

# Soma
so = n1 + n2

# Subtração
su = n1 - n2

# Multiplicação
mu = n1 * n2

# Divisão
div = n1 / n2

# Divisão Inteira
di = n1 // n2

# Exponensiação
ex = n1 ** n2

print('A soma é {}, o produto é {} e a divisão é {}'.format(so, mu, div), end=' ')
print('Divisão Inteira {} e potência {}'.format(di, ex))